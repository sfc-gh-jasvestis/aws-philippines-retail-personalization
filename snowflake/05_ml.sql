-- Member opt-out risk scoring and offer-issue forecast over the synthetic snapshot.
-- Predicts P(member opt-out for the segment in the next 7 days) per segment and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.OPTOUT_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, a.CATEGORY, a.RISK_TIER, a.MEMBER_TENURE_YEARS,
       r.IGNORE_RATE_PCT, r.CONTACTS_PER_MEMBER_WK,
       AVG(r.IGNORE_RATE_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS IGNORE_RATE_7D,
       SUM(r.OPTOUT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS OPTOUTS_30D,
       IFF(SUM(r.OPTOUT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'OPTOUT', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.SEGMENT_DAILY r JOIN RAW.SEGMENTS a ON a.ID = r.ENTITY_ID
-- City-wide SMS gateway outages are not segment-driven, so they are excluded from training.
WHERE r.ISSUE_TYPE <> 'SMS gateway outage';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.OPTOUT_TRAIN AS
SELECT CATEGORY, RISK_TIER, MEMBER_TENURE_YEARS, IGNORE_RATE_PCT, CONTACTS_PER_MEMBER_WK, IGNORE_RATE_7D, OPTOUTS_30D, LABEL
FROM ML.OPTOUT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.OPTOUT_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, RISK_TIER, MEMBER_TENURE_YEARS, IGNORE_RATE_PCT, CONTACTS_PER_MEMBER_WK, IGNORE_RATE_7D, OPTOUTS_30D, LABEL
FROM ML.OPTOUT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.OPTOUT_RISK_MODEL(
  INPUT_DATA => TABLE(ML.OPTOUT_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.OPTOUT_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.OPTOUT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'MEMBER_TENURE_YEARS', MEMBER_TENURE_YEARS,
           'IGNORE_RATE_PCT', IGNORE_RATE_PCT, 'CONTACTS_PER_MEMBER_WK', CONTACTS_PER_MEMBER_WK,
           'IGNORE_RATE_7D', IGNORE_RATE_7D, 'OPTOUTS_30D', OPTOUTS_30D)):probability:OPTOUT::FLOAT AS P
  FROM ML.OPTOUT_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'OPTOUT', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'OPTOUT', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'OPTOUT', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'OPTOUT', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per segment (label unknown, so excluded from features).
CREATE TABLE ML.OPTOUT_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.OPTOUT_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.OPTOUT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'MEMBER_TENURE_YEARS', MEMBER_TENURE_YEARS,
           'IGNORE_RATE_PCT', IGNORE_RATE_PCT, 'CONTACTS_PER_MEMBER_WK', CONTACTS_PER_MEMBER_WK,
           'IGNORE_RATE_7D', IGNORE_RATE_7D, 'OPTOUTS_30D', OPTOUTS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:OPTOUT::FLOAT, 4) AS OPTOUT_PROB_7D,
       CASE WHEN P:probability:OPTOUT::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:OPTOUT::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Program-wide offer-issue forecast (14 days) from the daily series, for CRM team staffing.
CREATE VIEW ML.DAILY_ISSUES AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(ISSUE_COUNT)::FLOAT AS ISSUE_COUNT
FROM RAW.SEGMENT_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.ISSUE_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_ISSUES),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'ISSUE_COUNT'
);

CREATE TABLE ML.ISSUE_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS ISSUE_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.ISSUE_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
