-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT segment.ID AS ENTITY_ID, segment.NAME AS ENTITY_NAME,
       segment.REGION, segment.CATEGORY, segment.RISK_TIER, segment.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.OFFER_COUNT) AS OFFER_COUNT,
       SUM(observation.SALES_PHP) AS SALES_PHP,
       SUM(observation.ISSUE_COUNT) AS ISSUE_COUNT,
       SUM(observation.OPTOUT_COUNT) AS OPTOUT_COUNT,
       SUM(observation.SPAM_REPORT) AS SPAM_REPORT_COUNT,
       SUM(observation.REFRESH_DUE) AS REFRESH_DUE,
       SUM(observation.REFRESH_DONE) AS REFRESH_DONE,
       100.0 * (SUM(observation.OFFER_COUNT) - SUM(observation.ISSUE_COUNT)) / NULLIF(SUM(observation.OFFER_COUNT), 0) AS CLEAN_OFFER_PCT,
       100.0 * SUM(observation.OPTOUT_COUNT) / NULLIF(SUM(observation.ISSUE_COUNT), 0) AS ISSUE_OPTOUT_PCT,
       100.0 * SUM(observation.REFRESH_DONE) / NULLIF(SUM(observation.REFRESH_DUE), 0) AS REFRESH_PCT,
       AVG(observation.IGNORE_RATE_PCT) AS AVG_IGNORE_RATE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.SEGMENT_DAILY observation
JOIN RAW.SEGMENTS segment ON segment.ID = observation.ENTITY_ID
GROUP BY segment.ID, segment.NAME, segment.REGION, segment.CATEGORY, segment.RISK_TIER, segment.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(OFFER_COUNT) AS OFFER_COUNT, SUM(SALES_PHP) AS SALES_PHP,
       SUM(ISSUE_COUNT) AS ISSUE_COUNT, SUM(OPTOUT_COUNT) AS OPTOUT_COUNT,
       100.0 * SUM(OPTOUT_COUNT) / NULLIF(SUM(ISSUE_COUNT), 0) AS ISSUE_OPTOUT_PCT
FROM RAW.SEGMENT_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.ISSUE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ISSUE_TYPE, SUM(ISSUE_COUNT) AS ISSUE_COUNT,
       SUM(OPTOUT_COUNT) AS OPTOUT_COUNT,
       SUM(SPAM_REPORT) AS SPAM_REPORT_COUNT,
       SUM(SALES_PHP) AS EXPOSED_SALES_PHP,
       100.0 * SUM(OPTOUT_COUNT) / NULLIF(SUM(ISSUE_COUNT), 0) AS ISSUE_OPTOUT_PCT
FROM RAW.SEGMENT_DAILY
WHERE ISSUE_COUNT > 0
GROUP BY ISSUE_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(OFFER_COUNT) AS OFFERS, SUM(ISSUE_COUNT) AS ISSUES,
         SUM(OPTOUT_COUNT) AS OPTOUTS, SUM(SPAM_REPORT) AS SPAM_REPORTS, SUM(SALES_PHP) AS SALES_PHP,
         SUM(REFRESH_DUE) AS REFRESH_DUE, SUM(REFRESH_DONE) AS REFRESH_DONE,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.SEGMENT_DAILY
), book AS (SELECT COUNT(*) AS SEGMENT_COUNT FROM RAW.SEGMENTS),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.CONSENT_RECORDS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Clean Offer Rate' AS TITLE,
         100.0 * (OFFERS - ISSUES) / NULLIF(OFFERS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Offer Issues Raised', ISSUES, '' FROM observations
  UNION ALL SELECT 3, 'Member Opt-outs', OPTOUTS, '' FROM observations
  UNION ALL SELECT 4, 'Issue Opt-out Rate', 100.0 * OPTOUTS / NULLIF(ISSUES, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Spam Reports', SPAM_REPORTS, '' FROM observations
  UNION ALL SELECT 6, 'Attributed Sales (PHP M)', SALES_PHP / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Offers Sent', OFFERS, '' FROM observations
  UNION ALL SELECT 8, 'Offer Refresh Compliance', 100.0 * REFRESH_DONE / NULLIF(REFRESH_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Segments Monitored', SEGMENT_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Consent Record Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Consent Records Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.ISSUE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
